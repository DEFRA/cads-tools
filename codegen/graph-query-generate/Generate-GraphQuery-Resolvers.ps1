# PowerShell script: run from repo root
param(
    [string]$Domain = 'All',
    [string]$RootPath = '../../../cads-data-service/src/Modules/Cads.Cds.SystemAdmin/Cads.Cds.SystemAdmin.Infrastructure/GraphQL',
    [string]$RootNamespace = 'Cads.Cds.SystemAdmin.Infrastructure.GraphQL'
)

$QueryClassName = 'GraphQuery'
$DbContextClassName = 'GraphQLDbContext'

if ([string]::IsNullOrWhiteSpace($Domain)) {
    $DbContextPath = $RootPath + '/Schemas/Contexts/' + $DbContextClassName + '.cs'
    $OutputPath = $RootPath + '/Queries/' + $QueryClassName + '.Generated.cs'
   
    $ContextNamespace = $RootNamespace + '.Schemas.Contexts'
    $EntitiesNamespace = $RootNamespace + '.Schemas.Entities'
    $QueriesNamespace = $RootNamespace + '.Schemas.Queries'
}
else {  
    $DbContextPath = $RootPath + '/Schemas/' + $Domain + '/Contexts/' + $Domain + $DbContextClassName + '.cs'
    $OutputPath = $RootPath + '/Schemas/' + $Domain + '/Queries/' + $Domain + $QueryClassName + '.Generated.cs'

    $QueryClassName = $Domain + $QueryClassName
    $DbContextClassName = $Domain + $DbContextClassName  

    $ContextNamespace = $RootNamespace + '.Schemas.' + $Domain + '.Contexts'
    $EntitiesNamespace = $RootNamespace + '.Schemas.' + $Domain + '.Entities'
    $QueriesNamespace = $RootNamespace + '.Schemas.' + $Domain + '.Queries'
}

$content = Get-Content $DbContextPath -Raw

# match lines like: public virtual DbSet<AnimalSex> AnimalSexes { get; set; }
$regex = 'public\s+virtual\s+DbSet<\s*([^>]+)\s*>\s+(\w+)\s*\{\s*get;\s*set;\s*\}'

$matches = [regex]::Matches($content, $regex)

$methods = foreach ($m in $matches) {
    $type = $m.Groups[1].Value.Trim()
    $prop = $m.Groups[2].Value.Trim()
    $methodName = "Get$prop"
    @"
    [UsePaging]     // Enables pagination
    [UseProjection] // Allows selecting nested fields
    [UseFiltering]  // Enables filtering
    [UseSorting]    // Enables sorting
    public IQueryable<$type> $methodName([Service] $DbContextClassName db) => db.$prop;
"@
}

$header = @"
// <auto-generated />
using $ContextNamespace;
using $EntitiesNamespace;
using HotChocolate;
using HotChocolate.Data;
using HotChocolate.Types;
using System.Linq;

namespace $QueriesNamespace;

// Generated using the HotChocolate GraphQL code generator (see CADS Tools)
// .\cads-tools\codegen\graph-query-generate\Generate-GraphQuery-Resolvers.ps1
public partial class $QueryClassName
{
"@

$footer = @"
}
"@

$generated = $header + ($methods -join "`n") + $footer

# Ensure directory exists
$dir = Split-Path $OutputPath
if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }

Set-Content -Path $OutputPath -Value $generated -Encoding UTF8

Write-Host "Generated $($matches.Count) resolver methods to $OutputPath"